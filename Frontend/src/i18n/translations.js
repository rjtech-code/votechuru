function pick(node, index) {
  if (Array.isArray(node)) return node[index]
  return Object.fromEntries(Object.entries(node).map(([key, value]) => [key, pick(value, index)]))
}

/** Glossary items are [termHi, termEn, definitionHi, definitionEn]; reshape them for pick(). */
function glossary(items) {
  return Object.fromEntries(
    Object.entries(items).map(([key, [termHi, termEn, defHi, defEn]]) => [key, { term: [termHi, termEn], definition: [defHi, defEn] }]),
  )
}
messages.pages.voterInfo.terms.items = glossary(messages.pages.voterInfo.terms.items)

